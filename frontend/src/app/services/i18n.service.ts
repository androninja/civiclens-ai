@Injectable({
  providedIn: 'root'
})
export class I18nService {
  currentLang = signal<string>('en');

  constructor() {
    if (typeof window !== 'undefined') {
      const stored = localStorage.getItem('civiclens_lang');
      if (stored && TRANSLATIONS[stored]) {
        this.currentLang.set(stored);
      }
    }
  }

  setLanguage(lang: string) {
    if (TRANSLATIONS[lang]) {
      this.currentLang.set(lang);
      if (typeof window !== 'undefined') {
        localStorage.setItem('civiclens_lang', lang);
      }
    }
  }

  t(key: string): string {
    const lang = this.currentLang();
    const table = TRANSLATIONS[lang] || TRANSLATIONS['en'];
    return table[key] || TRANSLATIONS['en'][key] || key;
  }

  getSupportedLanguages(): SupportedLanguage[] {
    return SUPPORTED_LANGUAGES;
  }

  getSpeechCode(langCode: string): string {
    const found = SUPPORTED_LANGUAGES.find(l => l.code === langCode);
    return found ? found.speechCode : 'en-IN';
  }
}
